import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {createServer} from 'vite';
import {canSelectTicket,nextQuantity,validQuantity} from '../src/pages/ticketSelection.js';
const standard={id:1,name:'General Admission',description:'Standing area access',price:'49.99',available:498,min_per_order:1,max_per_order:10,is_on_sale:true,sale_status:'on_sale'};
const vip={...standard,id:2,name:'VIP',price:'149.99'};
const paused={...standard,id:3,name:'Early Bird',is_on_sale:false,sale_status:'paused'};
assert.equal(nextQuantity(standard,0,1),1);
assert.equal(nextQuantity(standard,1,-1),0);
assert.equal(nextQuantity(standard,10,1),10);
const group={...standard,min_per_order:3,max_per_order:5,available:4};
assert.equal(nextQuantity(group,0,1),3);
assert.equal(nextQuantity(group,3,-1),0);
assert.equal(nextQuantity(group,4,1),4);
assert.equal(canSelectTicket({...group,available:2}),false);
assert.equal(nextQuantity({...group,available:2},0,1),0);
for(const quantity of [-1,0.5,11,'bad',Infinity])assert.equal(validQuantity(standard,quantity),0);
assert.equal(validQuantity(paused,2),0);
assert.equal(nextQuantity(paused,0,1),0);
const server=await createServer({server:{middlewareMode:true,hmr:false,ws:false},appType:'custom'});
try {
 const {default:EventTickets}=await server.ssrLoadModule('/src/pages/EventTickets.jsx');
 const render=(selection={},ticketTypes=[paused,standard,vip])=>renderToStaticMarkup(React.createElement(EventTickets,{ticketTypes,selection,onQuantity:()=>{},onCheckout:()=>{}}));
 const empty=render();
 assert.match(empty,/No tickets selected/);assert.match(empty,/disabled=""[^>]*>Choose your tickets/);
 assert.match(empty,/General Admission/);
 assert.match(empty,/<details class="event-pass-details"><summary>.*?View details.*?<\/summary><p>Standing area access<\/p><\/details>/);
 assert.doesNotMatch(empty,/<details[^>]*\bopen(?:=|\s|>)/);
 assert.doesNotMatch(render({},[{...standard,description:'   '}]),/event-pass-details/);
 assert.doesNotMatch(empty,/Early Bird|Sales paused/);
 assert.doesNotMatch(render({3:2},[{...standard,id:3,name:'Disabled pass',is_active:0}]),/Disabled pass/);
 assert.equal(canSelectTicket({...standard,is_active:0}),false);
 assert.match(render({},[{...standard,name:'Scheduled pass',is_on_sale:false,sale_status:'scheduled'}]),/Scheduled pass/);
 assert.match(render({},[{...standard,name:'Sold out pass',is_on_sale:false,sale_status:'sold_out'}]),/Sold out pass/);
 assert.match(render({},[paused]),/Tickets are on their way/);
 assert.doesNotMatch(empty,/aria-label="Add Early Bird ticket"/);
 const selected=render({1:2,2:1});
 assert.match(selected,/3 tickets selected/);assert.match(selected,/₹249\.97/);assert.match(selected,/Continue to booking/);assert.match(selected,/event-pass is-selected/);
 assert.match(selected,/aria-label="General Admission quantity"/);
 assert.match(render({1:10}),/aria-label="Add General Admission ticket" disabled=""/);
 assert.match(render({1:1},[{...standard,price:0}]),/Free/);
 assert.match(render({},[]),/Tickets are on their way/);
 assert.match(render({3:2},[paused]),/No tickets selected/);
 console.log('PASS ticket selection: totals, selected cards, paused/free/empty tickets, restored quantities, minimum and maximum limits.');
} finally {await server.close();}
