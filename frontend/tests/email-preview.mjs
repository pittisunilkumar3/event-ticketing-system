import assert from 'node:assert/strict';
import {requestEmailPreview,previewFormat} from '../src/admin/studio/emailPreview.js';
const timers=new Map();let id=0;
const clock={setTimeout(fn,delay){timers.set(++id,{fn,delay});return id;},clearTimeout(id){timers.delete(id);}};
const calls=[],results=[],errors=[];let settled=0;
const api={post(url,body,options){let resolve,reject;const promise=new Promise((a,b)=>{resolve=a;reject=b;});calls.push({url,body,options,resolve,reject});return promise;}};
const cb={success:r=>results.push(r),error:e=>errors.push(e),settled:()=>settled++};
let cancel=requestEmailPreview(api,{title:'Old'},'',cb,0,clock);
const first=timers.get(1).fn();cancel();
const stop=requestEmailPreview(api,{title:'New'},'5',cb,150,clock);assert.equal(timers.get(2).delay,150);const second=timers.get(2).fn();
calls[1].resolve({data:{data:{html:'new',formats:{1:'format one',8:'format eight'}}}});await second;
calls[0].resolve({data:{data:{html:'old'}}});await first;
assert.equal(results.length,1);assert.equal(results[0].html,'new');assert.equal(settled,1);
assert.equal(previewFormat(results[0],1),'format one');assert.equal(previewFormat(results[0],8),'format eight');assert.equal(calls.length,2);
assert.equal(calls[1].body.preview_formats,true);assert.equal(calls[1].body.ticket_type_id,'5');assert.equal(calls[1].options.timeout,15000);
stop();assert(calls[1].options.signal.aborted);
const pending=requestEmailPreview(api,{},'',cb,150,clock);pending();assert.equal(timers.has(3),false);
requestEmailPreview(api,{},'',cb,0,clock);const failed=timers.get(4).fn();calls[2].reject(new Error('bad preview'));await failed;assert.equal(errors.length,1);assert.equal(settled,2);
console.log('PASS email preview: immediate layout selection, 150ms edit debounce, timeout, canceled/stale response suppression, errors and cleanup.');
