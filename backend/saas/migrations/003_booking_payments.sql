CREATE TABLE IF NOT EXISTS booking_payments (
 id VARCHAR(36) PRIMARY KEY,
 organization_id INT UNSIGNED NOT NULL,
 event_id INT UNSIGNED NOT NULL,
 order_id INT UNSIGNED NOT NULL,
 request_hash CHAR(64) NOT NULL,
 key_id VARCHAR(120) NOT NULL,
 mode ENUM('test','live') NOT NULL,
 amount_minor BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'USD',
 status ENUM('creating','pending','paid','expired','review','refund_pending','refunded') NOT NULL DEFAULT 'creating',
 provider_order_id VARCHAR(100) NULL UNIQUE,
 provider_payment_id VARCHAR(100) NULL UNIQUE,
 provider_refund_id VARCHAR(100) NULL,
 expires_at DATETIME NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_booking_request(organization_id,request_hash),
 UNIQUE KEY uq_booking_order(organization_id,order_id),
 FOREIGN KEY(organization_id) REFERENCES organizations(id),
 INDEX idx_booking_expiry(status,expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS wallet_withdrawals (
 id VARCHAR(36) PRIMARY KEY,
 organization_id INT UNSIGNED NOT NULL,
 event_id INT UNSIGNED NOT NULL,
 event_title VARCHAR(255) NOT NULL,
 amount DECIMAL(14,2) NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'USD',
 status ENUM('pending','approved','rejected','cancelled','paid') NOT NULL DEFAULT 'pending',
 request_key VARCHAR(80) NOT NULL,
 bank_encrypted LONGTEXT NOT NULL,
 bank_last4 VARCHAR(4) NOT NULL,
 requested_by INT UNSIGNED NOT NULL,
 reviewed_by INT UNSIGNED NULL,
 review_note VARCHAR(500) NULL,
 transfer_reference VARCHAR(150) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 reviewed_at DATETIME NULL,
 paid_at DATETIME NULL,
 UNIQUE KEY uq_withdrawal_request(organization_id,request_key),
 UNIQUE KEY uq_withdrawal_transfer(transfer_reference),
 INDEX idx_withdrawal_event(organization_id,event_id,status),
 FOREIGN KEY(organization_id) REFERENCES organizations(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
