CREATE TABLE IF NOT EXISTS discount_coupons (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 kind ENUM('percentage','fixed') NOT NULL,
 value_units BIGINT UNSIGNED NOT NULL,
 event_id INT UNSIGNED NULL,
 ticket_type_ids TEXT NOT NULL,
 min_subtotal_minor BIGINT UNSIGNED NOT NULL DEFAULT 0,
 max_discount_minor BIGINT UNSIGNED NULL,
 usage_limit INT UNSIGNED NULL,
 per_email_limit INT UNSIGNED NULL,
 starts_at DATETIME NULL,
 ends_at DATETIME NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(event_id) REFERENCES events(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
