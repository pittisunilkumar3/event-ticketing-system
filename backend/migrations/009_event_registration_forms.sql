CREATE TABLE IF NOT EXISTS event_registration_forms (
 event_id INT UNSIGNED PRIMARY KEY,
 config_json LONGTEXT NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_registration_event FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS registration_form_templates (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 config_json LONGTEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS order_registration_answers (
 order_id INT UNSIGNED PRIMARY KEY,
 form_json LONGTEXT NOT NULL,
 answers_json LONGTEXT NOT NULL,
 CONSTRAINT fk_registration_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS registration_answer_files (
 order_id INT UNSIGNED NOT NULL,
 field_id VARCHAR(50) NOT NULL,
 file_name VARCHAR(180) NOT NULL,
 mime_type VARCHAR(80) NOT NULL,
 file_data MEDIUMBLOB NOT NULL,
 PRIMARY KEY(order_id,field_id),
 CONSTRAINT fk_registration_file_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
